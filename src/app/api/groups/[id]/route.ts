import { NextRequest, NextResponse } from "next/server";
import { Prisma } from "@prisma/client";
import { db } from "@/lib/db";
import { groupSchema, serializeGroup } from "../_shared";

export const dynamic = "force-dynamic";

type Ctx = { params: Promise<{ id: string }> };

function isNotFound(error: unknown): boolean {
  return error instanceof Prisma.PrismaClientKnownRequestError && error.code === "P2025";
}

/** GET /api/groups/[id] — one group. */
export async function GET(_req: NextRequest, ctx: Ctx) {
  try {
    const { id } = await ctx.params;
    const group = await db.livestockGroup.findUnique({ where: { id } });
    if (!group) return NextResponse.json({ error: "Group not found" }, { status: 404 });
    return NextResponse.json(serializeGroup(group));
  } catch (error) {
    console.error("GET /api/groups/[id] failed", error);
    return NextResponse.json({ error: "Failed to load group" }, { status: 500 });
  }
}

/** PUT /api/groups/[id] — full update. */
export async function PUT(req: NextRequest, ctx: Ctx) {
  try {
    const { id } = await ctx.params;
    const body = await req.json().catch(() => null);
    const parsed = groupSchema.safeParse(body);
    if (!parsed.success) {
      return NextResponse.json(
        { error: parsed.error.issues[0]?.message ?? "Invalid group data" },
        { status: 400 }
      );
    }
    const updated = await db.livestockGroup.update({ where: { id }, data: parsed.data });
    return NextResponse.json(serializeGroup(updated));
  } catch (error) {
    if (isNotFound(error)) return NextResponse.json({ error: "Group not found" }, { status: 404 });
    console.error("PUT /api/groups/[id] failed", error);
    return NextResponse.json({ error: "Failed to update group" }, { status: 500 });
  }
}

/**
 * DELETE /api/groups/[id] — hard delete.
 * The group's health events/vaccinations cascade; animals, tasks, activities and
 * transactions keep existing with groupId cleared (SetNull). Open vaccination
 * reminder tasks generated by the group's vaccinations are removed explicitly.
 */
export async function DELETE(_req: NextRequest, ctx: Ctx) {
  try {
    const { id } = await ctx.params;
    const vaccinations = await db.vaccination.findMany({ where: { groupId: id }, select: { id: true } });
    await db.task.deleteMany({
      where: { vaccinationId: { in: vaccinations.map((v) => v.id) }, status: "open" },
    });
    await db.livestockGroup.delete({ where: { id } });
    return NextResponse.json({ ok: true });
  } catch (error) {
    if (isNotFound(error)) return NextResponse.json({ error: "Group not found" }, { status: 404 });
    console.error("DELETE /api/groups/[id] failed", error);
    return NextResponse.json({ error: "Failed to delete group" }, { status: 500 });
  }
}
